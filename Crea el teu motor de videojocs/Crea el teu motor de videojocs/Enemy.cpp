#include "Enemy.h"

////////////////////////////////////////////////////////
// Constructor
////////////////////////////////////////////////////////
Enemy::Enemy(float x, float y)
    : Character(x, y, 120, -300)
{
    shape.setFillColor(Color::Red);
}

////////////////////////////////////////////////////////
// No usa teclado
////////////////////////////////////////////////////////
void Enemy::handleInput() {}

////////////////////////////////////////////////////////
// IA
// Se mueve y rebota en bordes
////////////////////////////////////////////////////////
void Enemy::ai(int MaxX)
{
    velocity.x = speed * direction;

    float width = shape.getSize().x;

    if (position.x <= 0)
        direction = 1;

    if (position.x >= MaxX - width)
        direction = -1;
}
